import { expect, test } from "@playwright/test";
import { randomSpot } from "../helpers";
const SHOTS = "/private/tmp/claude-501/-Users-alitaheri-Documents-source-gps-game/33925948-cfe2-48f9-9acb-89f26ab023ba/scratchpad/form";
test("ride form", async ({ page }) => {
  const errs: string[] = [];
  page.on("pageerror", (e) => errs.push(e.message));
  page.on("console", (m) => m.type() === "error" && errs.push("console: " + m.text()));
  page.on("response", async (r) => { if (r.url().includes("/api/rides")) console.log("RESP", r.request().method(), r.status(), (await r.text().catch(() => "")).slice(0, 200)); });
  await page.addInitScript(() => { const hide = () => document.head?.insertAdjacentHTML("beforeend", "<style>nextjs-portal{display:none!important}</style>"); if (document.head) hide(); else document.addEventListener("DOMContentLoaded", hide); localStorage.setItem("sq_tour_v2", "1"); localStorage.setItem("sq_mode_never", "1"); localStorage.setItem("sq_push_asked", "1"); });
  const spot = randomSpot();
  await page.context().setExtraHTTPHeaders({ "x-forwarded-for": "10.9.8.6" });
  await page.context().grantPermissions(["geolocation"]);
  await page.context().setGeolocation({ latitude: spot.lat, longitude: spot.lng, accuracy: 10 });
  await page.goto("/play");
  await expect(page.locator("nav.nav")).toBeVisible({ timeout: 60000 });
  await page.waitForTimeout(3000);
  await page.locator("nav.nav").getByText("Jobs").click();
  const gotIt = page.getByRole("button", { name: /got it/i });
  if (await gotIt.isVisible().catch(() => false)) await gotIt.click();
  await page.getByRole("tab", { name: /Rides/ }).click();
  await page.waitForTimeout(1200);
  await page.screenshot({ path: SHOTS + "/1-open.png" });
  await page.locator(".ride-request").getByRole("button", { name: /Pick/ }).nth(1).click();
  await page.waitForTimeout(600);
  await page.screenshot({ path: SHOTS + "/2-picking.png" });
  const box = (await page.locator(".leaflet-container").boundingBox())!;
  await page.mouse.click(box.x + box.width * 0.8, box.y + box.height * 0.2);
  await page.waitForTimeout(800);
  await page.screenshot({ path: SHOTS + "/3-picked.png" });
  await page.getByPlaceholder("e.g. Central station").fill("Central station");
  const fare = page.locator(".ride-request input[type=number]");
  console.log("FARE value", await fare.inputValue());
  await fare.fill("");
  console.log("FARE after clear", await fare.inputValue());
  await fare.pressSequentially("60");
  console.log("FARE after type 60", await fare.inputValue());
  await page.locator(".ride-request").evaluate((el) => el.scrollIntoView({ block: "end" }));
  await page.screenshot({ path: SHOTS + "/4-filled.png" });
  const btn = page.getByRole("button", { name: /Request car/ });
  console.log("BTN disabled", await btn.isDisabled(), await btn.textContent());
  await btn.click();
  await page.waitForTimeout(2000);
  await page.screenshot({ path: SHOTS + "/5-after.png" });
  console.log("ERRS", JSON.stringify(errs));
});
